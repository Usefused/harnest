"""Opt-in compiled ADK/LangGraph probe using a real model and real Docker.

Install ``harnest-extension-docker`` and run this file with ``OPENAI_API_KEY``
and access to the selected Docker daemon. Only synthetic probe input is sent to
the model; containers receive no host credentials or mounts.
"""

