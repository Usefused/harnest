def _write(path: Path, value: str) -> None:
    """Materialize temporary authored inputs, never mutate an existing agent."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8")


def _source(root: Path, config: dict, journal: Path) -> None:
    """Author the same portable provider and model for either managed framework."""
    prefix = f"CONFIG = {config!r}\nJOURNAL = {str(journal)!r}\n"
    files = {
        "agent.py": _AGENT,
        "instructions.md": _INSTRUCTIONS,
        "agent-card.yaml": "name: Sandbox live\ndescription: Synthetic sandbox probe\nversion: 0.1.0\n",
        "lib/provider.py": prefix + _PROVIDER,
        "lib/sandbox_config.py": _SANDBOX,
        "extensions/storage.py": _STORAGE,
    }
    for relative, value in files.items():
        _write(root / relative, value)


def _assert_execution(records: list, response: dict, expected: str) -> dict:
    """Require evidence from Docker, the portable contract, and model follow-up."""
    executions = [entry for entry in records if entry["event"] == "execute"]
    assert executions, "model did not execute the sandbox"
    execution = executions[-1]
    _assert_output(execution["stdout"], expected)
    assert expected in response["text"], "model lost the real execution output"
    assert execution["metadata"]["receipt"] in response["text"], "model lost provider metadata"
    assert execution["context"]["agent_name"] == "sandbox_live"
    assert all(execution["context"].values()), "missing managed request identity"
    return {"executions": executions, "model_output": response["text"]}


def _assert_output(stdout: str, expected: str) -> None:
    """Check the computed nonce and actual container platform independently."""
    output = json.loads(stdout)
    assert output["sha256"] == expected, output
    assert output["platform"] == "Linux", output
    assert output["python"].startswith("3.12."), output


async def _framework(framework: str, config: dict, evidence: Path) -> dict:
    """Compile and invoke a real native model loop with bounded synthetic work."""
    with tempfile.TemporaryDirectory(prefix=f"harnest-sandbox-{framework}-") as directory:
        root = Path(directory)
        journal = root / "provider.jsonl"
        _source(root / "source", config, journal)
        compile_artifact(root / "source", root / "artifact", framework=framework)
        assert not journal.exists(), "compilation constructed the provider"
        nonce = "synthetic-sandbox-" + uuid.uuid4().hex
        code = (
            "import hashlib, json, platform\n"
            f"print(json.dumps({{'sha256': hashlib.sha256({nonce!r}.encode()).hexdigest(), "
            "'platform': platform.system(), 'python': platform.python_version()}))"
        )
        prompt = (
            "Execute this exact Python in the sandbox once; do not calculate it yourself.\n"
            + code + "\nAfter execution, return the computed sha256 and the provider's receipt "
            "from result metadata. The receipt is generated by the provider, not by the code."
        )
        try:
            response = await run_agent_message(root / "artifact", prompt, request_timeout=90)
        finally:
            records = [json.loads(line) for line in journal.read_text().splitlines()]
            _write(evidence, json.dumps(records, indent=2) + "\n")
        return _assert_execution(records, response, hashlib.sha256(nonce.encode()).hexdigest())


def main() -> int:
    """Keep paid provider calls opt-in and persist only synthetic test evidence."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", default="python:3.12-slim")
    parser.add_argument("--base-url", required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    if not os.getenv("OPENAI_API_KEY"):
        parser.error("OPENAI_API_KEY is required; credentials are never written to the report")
    config = {"image": args.image, "base_url": args.base_url}
    report = {"model": os.getenv("OPENAI_MODEL", "gpt-4.1-mini"), "frameworks": {}}
    for framework in ("adk", "langgraph"):
        evidence = args.report.with_suffix(f".{framework}.json")
        try:
            result = asyncio.run(_framework(framework, config, evidence))
            report["frameworks"][framework] = {"status": "passed", **result}
        except Exception as error:
            report["frameworks"][framework] = {"status": "failed", "error_type": type(error).__name__}
        report["frameworks"][framework]["evidence"] = str(evidence)
        _write(args.report, json.dumps(report, indent=2) + "\n")
        print(f"live model + Docker {framework}: {report['frameworks'][framework]['status']}", flush=True)
    return int(any(result["status"] != "passed" for result in report["frameworks"].values()))


