def record(value):
    """Record only synthetic execution evidence, not model or SDK credentials."""
    with Path(JOURNAL).open("a", encoding="utf-8") as stream:
        stream.write(json.dumps(value) + "\\n")


class ModelEvidence(LiteLLMLifecycle):
    """Capture only synthetic model responses, never transport request credentials."""

    def after_response(self, response, context):
        """Retain actual model messages to diagnose missing native loop continuation."""
        record({"event": "model", "response": response.model_dump(exclude_none=True)})
        return response


class ReportingBackend:
    """Enrich real Docker results with safe, observed provider properties."""

    def __init__(self):
        """Configure every supported native option without allocating Docker."""
        self.calls = 0
        self.backend = docker_sandbox(
            **CONFIG, timeout_seconds=10,
            options={
                "error_retry_attempts": 1,
                "code_block_delimiters": [("```python\\n", "\\n```")],
                "execution_result_delimiters": ("<result>", "</result>"),
                "stateful": False, "optimize_data_file": False,
            },
        ).build()._backend

    def execute(self, request):
        """Run actual Docker execution and expose measured provider metadata."""
        self.calls += 1
        if self.calls > 3:
            raise RuntimeError("live probe exceeded its execution budget")
        assert request.metadata["labels"]["framework_neutral"] is True
        started = time.monotonic()
        result = self.backend.execute(request)
        native = self.backend._executor
        container = native._container
        container.reload()
        host = container.attrs["HostConfig"]
        metadata = {
            "receipt": uuid.uuid4().hex,
            "provider": "adk-native-docker",
            "versions": {key: version(key) for key in ("google-adk", "docker")},
            "container": {
                "id": container.id, "image_id": container.image.id,
                "architecture": container.image.attrs["Architecture"],
                "network_mode": host["NetworkMode"],
                "network_disabled": container.attrs["Config"]["NetworkDisabled"],
                "memory": host["Memory"], "nano_cpus": host["NanoCpus"],
                "cap_drop": host["CapDrop"], "security_opt": host["SecurityOpt"],
                "mounts": len(container.attrs["Mounts"]),
            },
            "options": native.model_dump(),
            "duration_ms": round((time.monotonic() - started) * 1000, 3),
            "request_metadata": sandbox_metadata_to_dict(request.metadata),
        }
        assert not container.attrs["Mounts"]
        assert host["Memory"] == host["NanoCpus"] == 0
        # Docker's disabled flag does not require HostConfig.NetworkMode="none".
        assert container.attrs["Config"]["NetworkDisabled"] is True
        record({
            "event": "execute", "stdout": result.stdout, "stderr": result.stderr,
            "metadata": metadata, "context": asdict(request.context),
            "code_sha256": hashlib.sha256(request.code.encode()).hexdigest(),
        })
        return SandboxResult(stdout=result.stdout, stderr=result.stderr, metadata=metadata)


def build():
    """Record lazy construction for the compile/runtime boundary assertion."""
    record({"event": "build"})
    return ReportingBackend()
